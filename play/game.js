function getTargetBgmKey() {
  const stageVal = typeof state !== "undefined" && state.mode === "play" ? state.stage : selectedStage;
  return stageVal === 2 || selectedHeroId === "vector_sprite" ? "digital" : "paper";
}

function syncBgmBtn() {
  if (!bgmBtn) return;
  bgmBtn.textContent = bgmEnabled ? "🎵 OST" : "🔇 OST";
  bgmBtn.setAttribute("aria-pressed", String(bgmEnabled));
}

function syncBgmPlayback(fromGesture = false) {
  if (fromGesture) bgmStarted = true;
  syncBgmBtn();
  if (!bgmEnabled || !bgmStarted) {
    ostPaper.pause();
    ostDigital.pause();
    return;
  }
  const target = getTargetBgmKey();
  if (currentBgmKey !== target) {
    ostPaper.pause();
    ostDigital.pause();
    currentBgmKey = target;
  }
  const activeTrack = target === "digital" ? ostDigital : ostPaper;
  if (activeTrack.paused) {
    activeTrack.play().catch(() => {});
  }
}

// Lightweight procedural Web Audio synthesizer ($0, no external audio assets)
let audioCtx = null;
function playSfx(kind) {
  if (!sfxEnabled) return;
  const AC = window.AudioContext || window.webkitAudioContext;
  if (!AC) return;
  if (!audioCtx) audioCtx = new AC();
  if (audioCtx.state === "suspended") audioCtx.resume().catch(() => {});

  const now = audioCtx.currentTime;
  const osc = audioCtx.createOscillator();
  const gain = audioCtx.createGain();
  osc.connect(gain);
  gain.connect(audioCtx.destination);

  if (kind === "jump") {
    osc.type = "triangle";
    osc.frequency.setValueAtTime(240, now);
    osc.frequency.exponentialRampToValueAtTime(480, now + 0.11);
    gain.gain.setValueAtTime(0.08, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.12);
    osc.start(now);
    osc.stop(now + 0.12);
  } else if (kind === "shift") {
    osc.type = "sine";
    osc.frequency.setValueAtTime(state.dim === "2D" ? 390 : 520, now);
    osc.frequency.exponentialRampToValueAtTime(state.dim === "2D" ? 590 : 340, now + 0.14);
    gain.gain.setValueAtTime(0.08, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.15);
    osc.start(now);
    osc.stop(now + 0.15);
  } else if (kind === "drop") {
    osc.type = "sine";
    osc.frequency.setValueAtTime(660, now);
    osc.frequency.exponentialRampToValueAtTime(990, now + 0.13);
    gain.gain.setValueAtTime(0.09, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.16);
    osc.start(now);
    osc.stop(now + 0.16);
  } else if (kind === "stroke" || kind === "power") {
    osc.type = "triangle";
    osc.frequency.setValueAtTime(kind === "power" ? 440 : 510, now);
    osc.frequency.exponentialRampToValueAtTime(kind === "power" ? 880 : 720, now + 0.18);
    gain.gain.setValueAtTime(0.09, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.2);
    osc.start(now);
    osc.stop(now + 0.2);
  } else if (kind === "hit") {
    osc.type = "sawtooth";
    osc.frequency.setValueAtTime(170, now);
    osc.frequency.exponentialRampToValueAtTime(80, now + 0.18);
    gain.gain.setValueAtTime(0.08, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.19);
    osc.start(now);
    osc.stop(now + 0.19);
  } else if (kind === "win") {
    osc.type = "triangle";
    osc.frequency.setValueAtTime(440, now);
    osc.frequency.setValueAtTime(554.37, now + 0.1);
    osc.frequency.setValueAtTime(659.25, now + 0.2);
    osc.frequency.setValueAtTime(880, now + 0.3);
    gain.gain.setValueAtTime(0.1, now);
    gain.gain.exponentialRampToValueAtTime(0.001, now + 0.65);
    osc.start(now);
    osc.stop(now + 0.65);
  }
}

